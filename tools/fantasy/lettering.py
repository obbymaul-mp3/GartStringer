def draw(put,x,y,s,k=1):
    """put(px,py,row_in_cell 0..13) for every lit pixel"""
    for c in s:
        t,r=G[c]
        for j,row in enumerate(r):
            for i,ch in enumerate(row):
                if ch=='#':
                    for a in range(k):
                        for b in range(k): put(x+i*k+a,y+(t+j)*k+b,t+j)
        x+=(len(r[0])+1)*k
