#!/usr/bin/env python3
"""The look of GartStringer 3: its palette, the six worlds' scenes, its lettering and its two sprites, as firmware/src/gs_art.h.

    python3 tools/gen_fantasy.py [preview.png] > firmware/src/gs_art.h

Everything here is drawn by this program (tools/fantasy/scenes.py paints the scenes, tools/fantasy/lettering.py holds the letters):
original work, nothing taken from a game. Needs numpy and Pillow; the header it writes is committed, so a build does not.
"""
import sys, os
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fantasy'))
import scenes, lettering
scenes.GHOSTS = scenes.FLIES = False

def hx(s): return tuple(int(s[i:i + 2], 16) for i in (1, 3, 5))
NIGHT, WB, WA, UNLIT, DIM, EDGE, LILAC, PARCH = map(hx, ('#0a0420', '#0e072c', '#26145c', '#2a1a66', '#5a3fa8', '#9a88e6', '#b9a8ff', '#f4e6c4'))
GOLD, GOLDHI, GOLDLO, PINK, PINKHI, PINKLO, INK = map(hx, ('#f2c14e', '#fff3c2', '#c98a2e', '#ff5fb4', '#ff9ad2', '#b0246f', '#1a0b33'))
def mix(a, b, t): return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(3))
BASE = [
    NIGHT,                                                            # C_BG
    WB, (26, 14, 64), UNLIT,                                          # C_K1..3: the panels
    (58, 36, 20), (90, 56, 24), (138, 92, 34), GOLDLO, (226, 166, 62), GOLD, (250, 216, 130), GOLDHI,   # C_O0..7: gold, dark to bright
    hx('#22145c'), hx('#46349a'), DIM, EDGE, LILAC, (220, 206, 236), PARCH,                             # C_S0..6: stone to parchment
    (70, 16, 56), PINKLO, (220, 64, 146), PINK, PINKHI,               # C_R0..4: pink
    (255, 255, 255),                                                  # C_HOT
] + [mix(WB, WA, i / 5) for i in range(6)] + [                        # C_B0..5: a window's ground, bottom to top
    PARCH, LILAC,                                                     # C_INK, C_INK2
    (30, 18, 74), GOLD, UNLIT, DIM, (122, 104, 190), DIM, WB,         # C_GRID0, C_LED, C_GRID1, C_GRID2, C_DIM, C_DIM2, C_PLATE
    (48, 224, 96), (160, 224, 48), (240, 224, 48), (255, 176, 32), (255, 106, 24), (255, 32, 48),       # C_BT0..5: the battery
    INK, hx('#9fb4e8'),                                               # C_OUT, C_STEEL
    hx('#f2c14e'), hx('#7a6cff'), hx('#ff5fb4'), hx('#4fd6c8'), hx('#ff8a4a'),                           # C_G0..4: the gems
    None,                                                             # C_WORLD: the world's own colour
    WA, (52, 18, 70), (12, 6, 36),                                    # C_WA, C_SEL, C_ROW
] + [mix(hx(c), INK, .34) for c in ('#f2c14e', '#7a6cff', '#ff5fb4', '#4fd6c8', '#ff8a4a')] + [   # C_GD0..4: the gems' lower halves
    (106, 42, 112), (0, 0, 0),                                        # C_VEIN: a string at rest; (spare)
]
assert len(BASE) == 64
WORLDS = [('castle', '#ff5fb4', 0, 240, 24), ('cathedral', '#ff8a4a', 30, 160, 32), ('dungeon', '#4fd6c8', 24, 160, 34),
          ('shrine', '#7a6cff', 40, 160, 28), ('forest', '#73ffbf', 40, 160, 22), ('forge', '#ff5980', 50, 160, 58)]
# (painter, the world's colour, the first row kept, rows kept, the row within those where the 90-row window starts)

_orig = scenes.fin
def _cap(a):
    _cap.last = a.copy()
    return _orig(a)
scenes.fin = _cap
B = np.tile(scenes.BAYER, (60, 60))[..., None] - .5
def near(src, pal): return np.concatenate([((src[i:i + 8000, None] - pal[None]) ** 2).sum(-1).argmin(1) for i in range(0, len(src), 8000)])
def quant(a, n=16, acc=5):
    """sixteen colours: eleven by median cut, then five for whatever those serve worst (a lit window, a pennant, a flame)"""
    a = np.clip(a, 0, 1); flat = a.reshape(-1, 3)
    q = Image.fromarray((a * 255).astype(np.uint8), 'RGB').quantize(colors=n - acc, method=Image.MEDIANCUT, dither=Image.NONE, kmeans=2)
    pal = np.array(q.getpalette()[:3 * (n - acc)], np.float32).reshape(-1, 3) / 255
    q5 = np.round(flat * 15) / 15
    for _ in range(acc):
        err = ((flat - pal[near(flat, pal)]) ** 2).sum(1)
        u, inv, cnt = np.unique(q5, axis=0, return_inverse=True, return_counts=True)
        inv = inv.reshape(-1)
        e = np.bincount(inv, weights=err) / cnt; e[cnt < 8] = 0
        pal = np.vstack([pal, flat[inv == e.argmax()].mean(0)])
    for _ in range(4):
        idx = near(flat, pal)
        for i in range(len(pal)):
            if (idx == i).any(): pal[i] = flat[idx == i].mean(0)
    idx = near((a + B * .07).reshape(-1, 3), pal)
    return idx.reshape(240, 240).astype(np.uint8), pal

out = []; W = out.append
W('/* Generated by tools/gen_fantasy.py - do not edit. The palette, the worlds\' scenes, the lettering, the sprites: all drawn by that program. */')
W('#define FB_RGB(r, g, b) (((uint32_t)(r) << 16) | ((uint32_t)(g) << 8) | (uint32_t)(b))')
themes = []; datas = []; prev = []
for n, (name, wc, y0, h, wy) in enumerate(WORLDS):
    getattr(scenes, name)()
    idx, pal = quant(_cap.last)
    prev.append(Image.fromarray((pal[idx] * 255).astype(np.uint8), 'RGB'))
    t = list(BASE); t[53] = hx(wc)
    t += [tuple(int(round(c * 255)) for c in p) for p in pal]
    themes.append(t)
    rows = idx[y0:y0 + h]
    datas.append((name, h, wy, (rows[:, 0::2] << 4 | rows[:, 1::2]).reshape(-1)))
W('static const uint32_t SK_THEME[FB_NTHEME][%d] = {' % len(themes[0]))
for t in themes:
    W('    {' + ', '.join('FB_RGB(%d, %d, %d)' % c for c in t) + '},')
W('};')
for name, h, wy, d in datas:
    W('static const uint8_t SCN_%s[%d] = {' % (name.upper(), len(d)))
    for i in range(0, len(d), 40): W('    ' + ','.join(str(int(v)) for v in d[i:i + 40]) + ',')
    W('};')
W('typedef struct { const uint8_t *d; uint8_t h, wy; } fb_scene_t;     /* 240 wide, two pixels a byte; h rows; the window shows 90 rows from wy */')
W('static const fb_scene_t SK_SCENE[FB_NTHEME] = {' + ', '.join('{SCN_%s, %d, %d}' % (n.upper(), h, wy) for n, h, wy, d in datas) + '};')
# the lettering: a glyph is its width, its first row and its rows (a row is 16 bits, the leftmost pixel the top bit)
rows = []; tab = []
for ch in range(128):
    g = lettering.G.get(chr(ch))
    if not g: tab.append((0, 0, 0, 0)); continue
    top, r = g; tab.append((len(rows), len(r[0]), top, len(r)))
    for line in r: rows.append(sum(1 << (15 - i) for i, c in enumerate(line) if c == '#'))
W('typedef struct { uint16_t off; uint8_t w, top, n; } bl_glyph_t;')
W('static const bl_glyph_t BL_G[128] = {' + ', '.join('{%d, %d, %d, %d}' % t for t in tab) + '};')
W('static const uint16_t BL_ROWS[%d] = {' % len(rows) + ', '.join(str(v) for v in rows) + '};')
# what moves in each scene when notes sound: places in it (x, y, a size), in the scene's own pixels here and the window's in the header
import random as _r
_rr = _r.Random(5)
SPOTS = [
    [(90, 54, 0), (95, 60, 0), (68, 74, 0), (114, 70, 0), (80, 86, 0), (104, 88, 0)],                                   # the towers' windows
    [(int(120 + sd * 1.05 * 120 / z), int(112 + 12 / z), int(round(5 / z))) for z in (1.2, 2.7, 4.2) for sd in (-1, 1)],  # the candles
    [(176, 84, 0), (66, 112, 1), (133, 98, 2)],                                                                        # the ghosts
    [(124, 94, 0), (60, 146, 4), (188, 146, 4), (124, 84, 1), (114, 76, 1), (134, 72, 1)],                              # the gem, the braziers, motes over the sword
    [(_rr.randrange(10, 230), _rr.randrange(106, 148), 0) for _ in range(16)],                                         # the fireflies
    [(30, 186, 0), (70, 188, 0), (104, 186, 0), (140, 187, 0), (176, 188, 0), (212, 186, 0)],                           # where the lava spits
]
W('static const uint8_t SCN_NSPOT[FB_NTHEME] = {' + ', '.join(str(len(sp)) for sp in SPOTS) + '};')
W('static const uint8_t SCN_SPOT[FB_NTHEME][16][3] = {      /* x and y in the window, a size */')
for (name, wc, y0, h, wy), sp in zip(WORLDS, SPOTS):
    for x, y, k in sp: assert 0 <= x - 9 < 222 and 0 <= y - y0 - wy < 90, (name, x, y)
    W('    {' + ', '.join('{%d, %d, %d}' % (x - 9, y - y0 - wy, k) for x, y, k in sp) + '},')
W('};')
# the ghosts, three sizes: 0 nothing, 1 the body, 2 its lit side, 3 an eye or the mouth
for gi, sz in enumerate((15, 10, 5)):
    w = 2 * sz + 1; h = int(sz * 2.8) + 2; cx = sz; cy = sz + 1
    g = np.zeros((h, w), np.uint8)
    for y in range(h):
        for x in range(w):
            body = (np.hypot((x - cx) / sz, (min(y, cy) - cy) / (sz * 1.1)) < 1) and y < cy + sz * 1.5 + round(np.sin((x - cx) / sz * 5) * sz * .22) and abs(x - cx) < sz
            if body: g[y, x] = 2 if (x < cx - sz * .35 and y < cy) else 1
    for e in (-.38, .38): g[int(cy - sz * .2):int(cy + sz * .22) + 1, int(cx + e * sz - sz * .14):int(cx + e * sz + sz * .14) + 1] = 3
    g[int(cy + sz * .45):int(cy + sz * .7) + 1, int(cx - sz * .12):int(cx + sz * .12) + 1] = 3
    W('static const uint8_t SPR_GHOST%d[%d] = {%d, %d, ' % (gi, 2 + w * h, w, h) + ', '.join(str(int(v)) for v in g.reshape(-1)) + '};')
W('static const uint8_t *const SPR_GHOST[3] = {SPR_GHOST0, SPR_GHOST1, SPR_GHOST2};')
SWORD = ["...k..........", "..kgk.........", "kkkgkkkkkkkk..", "kpgswwwwwwwwk.", "kpgsbbbbbbbbbk", "kkkgkkkkkkkk..", "..kgk.........", "...k.........."]
HEART = [".kk.kk.", "kppkppk", "kpwpppk", "kpppppk", ".kpppk.", "..kpk..", "...k..."]
CI = {'.': 255, 'k': 46, 'g': 9, 'p': 22, 's': 47, 'w': 24, 'b': 47}
for nm, sp in (('SWORD', SWORD), ('HEART', HEART)):
    W('static const uint8_t SPR_%s[%d][%d] = {' % (nm, len(sp), len(sp[0])) + ', '.join('{' + ', '.join(str(CI[c]) for c in r) + '}' for r in sp) + '};')
sys.stdout.write('\n'.join(out) + '\n')
if len(sys.argv) > 1:
    sh = Image.new('RGB', (3 * 240, 2 * 240))
    for i, im in enumerate(prev): sh.paste(im, ((i % 3) * 240, (i // 3) * 240))
    sh.save(sys.argv[1])
